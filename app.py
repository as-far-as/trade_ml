    {"Ticker": "CBRE",   "Entry": 129.42, "Target": 135.00, "Stop": 124.50, "Market": "US"},
    {"Ticker": "SAN.MC", "Entry": 10.298, "Target": 11.10,  "Stop": 10.20,  "Market": "ES"}, # Updated Stop
