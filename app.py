# --- CONFIGURATION & MODELS ---
WATCHLIST = [
    {"Ticker": "CBRE",   "Market": "US"},
    {"Ticker": "SAN.MC", "Market": "ES"},
    {"Ticker": "RTO.L",  "Market": "UK"},
    {"Ticker": "CSCO",   "Market": "US"},
    {"Ticker": "GLEN.L", "Market": "UK"},
]

@st.cache_resource
def load_assets():
    """Loads the trained ML model brain."""
    try:
        # Using the exact name generated by your trainer script
        model = joblib.load('models/random_forest_model.pkl')
        return model
    except Exception as e:
        st.error(f"ML Model (predictor.pkl) not found! {e}")
        return None

ml_model = load_assets()

# --- VISUALIZATION FUNCTIONS ---
def create_price_chart(df, ticker, buy_prob):
    """Creates an interactive Plotly chart with AI highlights."""
    fig = go.Figure()
    
    # Price Line
    fig.add_trace(go.Scatter(x=df.index, y=df['Close'], name='Price', line=dict(color='#00d4ff', width=2)))
    
    # 50-Day Moving Average
    fig.add_trace(go.Scatter(x=df.index, y=df['MA50'], name='50 MA', line=dict(color='rgba(255, 255, 255, 0.4)', dash='dash')))

    # Title & Theme
    fig.update_layout(
        title=f"{ticker} Momentum Analysis (AI Confidence: {buy_prob:.1%})",
        template="plotly_dark",
        xaxis_rangeslider_visible=False,
        height=400,
        margin=dict(l=20, r=20, t=50, b=20)
    )
    return fig

# --- APP LAYOUT ---
st.set_page_config(page_title="Trade AI: War Room", layout="wide")
st.title("🦅 Trade AI: Dip-Hunter Pro")

if st.sidebar.button('🔄 Refresh Global Markets'):
    st.cache_resource.clear()
    st.rerun()

# --- MAIN EXECUTION ---
dashboard_data = []
all_ticker_dfs = {}

with st.spinner('Synchronizing ETL Pipeline...'):
    for item in WATCHLIST:
        ticker = item["Ticker"]
        fetcher = DataFetcher(ticker)
        
        # 1. Extraction & Feature Engineering
        hist_df = fetcher.fetch_historical_data(period="1y")
        full_data = fetcher.add_indicators(hist_df)
        
        if full_data.empty:
            continue
            
        latest = full_data.iloc[-1]
        all_ticker_dfs[ticker] = full_data
        
        # 2. ML Inference
        # Order must match trainer.py: [RSI, MA50, MA200, Volatility, Volume]
        features = [[latest['RSI'], latest['MA50'], latest['MA200'], latest['Volatility'], latest['Volume']]]
        buy_prob = ml_model.predict_proba(features)[0][1] if ml_model else 0.5
        
        # 3. Risk Management Calculation (Dynamic based on Volatility)
        current_price = latest['Close']
        stop_buffer = current_price * (latest['Volatility'] * 2)
        
        dashboard_data.append({
            "Ticker": ticker,
            "Price": round(current_price, 2),
            "RSI": round(latest['RSI'], 1),
            "AI Conviction": buy_prob,
            "Stop Loss": round(current_price - stop_buffer, 2),
            "Target": round(current_price + (stop_buffer * 2), 2),
            "Vol": round(latest['Volatility'], 4)
        })

# --- UI COMPONENT: TOP TABLE ---
st.subheader("📡 Live Signals")
df_display = pd.DataFrame(dashboard_data)

# Heatmap styling for Conviction
def color_conviction(val):
    if val > 0.7: color = '#2ecc71'
    elif val < 0.3: color = '#e74c3c'
    else: color = 'transparent'
    return f'background-color: {color}'

st.dataframe(
    df_display.style.format({"AI Conviction": "{:.1%}"}).applymap(color_conviction, subset=['AI Conviction']),
    use_container_width=True,
    hide_index=True
)

# --- UI COMPONENT: DEEP DIVE VISUALS ---
st.markdown("---")
st.subheader("🔍 Technical Deep Dive")

# Create tabs for each ticker to keep UI clean
tabs = st.tabs([item["Ticker"] for item in WATCHLIST])

for i, tab in enumerate(tabs):
    ticker = WATCHLIST[i]["Ticker"]
    row = next(item for item in dashboard_data if item["Ticker"] == ticker)
    
    with tab:
        col_text, col_chart = st.columns([1, 2])
        
        with col_text:
            st.metric("ML Probability", f"{row['AI Conviction']:.1%}", delta=f"{row['AI Conviction']-0.5:.1%}")
            st.write(f"**Current RSI:** {row['RSI']}")
            st.write(f"**Risk/Reward:** {row['Stop Loss']} / {row['Target']}")
            
            # AI RATIONALE (LLM PLACEHOLDER)
            if row['AI Conviction'] > 0.7:
                st.success("High probability dip detected. Technical support confirms ML signal.")
            elif row['AI Conviction'] < 0.3:
                st.error("Negative momentum confirmed. RSI has not bottomed out yet.")
            else:
                st.warning("Neutral zone. Model awaiting clearer volume trend.")

        with col_chart:
            chart = create_price_chart(all_ticker_dfs[ticker], ticker, row['AI Conviction'])
            st.plotly_chart(chart, use_container_width=True)

st.caption("Deployment: Local Mac / Streamlit Cloud | Engine: Random Forest v1.0 | Data: yFinance (15m delay)")